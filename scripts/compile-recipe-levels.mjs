import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const recipelistPath = path.join(ROOT, 'api/recipelist.txt');
const staticOutPath = path.join(ROOT, 'static/recipe-levels.json');
const sampleOutPath = path.join(ROOT, 'static/recipe-levels.sample.json');
const tsOutPath = path.join(ROOT, 'src/lib/quest/calc/recipeLevels.ts');

const text = fs.readFileSync(recipelistPath, 'utf8');
const lines = text.split('\n').map((l) => l.trim());

const gates = {};

// 1. Parse Workshop recipes from api/recipelist.txt
let currentItem = null;
for (let i = 0; i < lines.length; i++) {
	if (lines[i] === 'Visible in Workshop' && i > 0) {
		currentItem = lines[i - 1];
	}
	const m = lines[i].match(/^Crafting Lv\s+(\d+)$/);
	if (m && currentItem) {
		gates[currentItem] = {
			skill: 'crafting',
			level: parseInt(m[1], 10)
		};
		currentItem = null;
	}
}

// 2. Add Kitchen Cooking Meals
const COOKING_MEALS = {
	'Bone Broth': { skill: 'cooking', level: 1 },
	'Onion Soup': { skill: 'cooking', level: 5, npc: 'George', npcLevel: 10 },
	'Over The Moon': { skill: 'cooking', level: 10, npc: 'ROOMBA', npcLevel: 20 },
	"Cat's Meow": { skill: 'cooking', level: 15, npc: 'Thomas', npcLevel: 30 },
	'Mushroom Stew': { skill: 'cooking', level: 20, npc: 'Holger', npcLevel: 40 },
	'Quandary Chowder': { skill: 'cooking', level: 25, npc: 'Jill', npcLevel: 50 },
	'Cabbage Stew': { skill: 'cooking', level: 25 },
	Neigh: { skill: 'cooking', level: 30, npc: 'Charles Horsington III', npcLevel: 40 },
	'Sea Pincher Special': { skill: 'cooking', level: 30, npc: 'Vincent', npcLevel: 50 },
	'Shrimp-a-Plenty': { skill: 'cooking', level: 35, npc: 'Cecil', npcLevel: 60 },
	'Hickory Omelette': { skill: 'cooking', level: 35, npc: 'Mariya', npcLevel: 40 },
	'Breakfast Boost': { skill: 'cooking', level: 40, npc: 'Lorn', npcLevel: 40 },
	'Red Berry Pie': { skill: 'cooking', level: 40, npc: 'Rosalie', npcLevel: 40 },
	'Concord Grape Pie': { skill: 'cooking', level: 40, npc: 'Rosalie', npcLevel: 50 },
	'Acorn Pie': { skill: 'cooking', level: 50, npc: 'George', npcLevel: 72 },
	'Crunchy Omelette': { skill: 'cooking', level: 35 },
	'Festive Eggnog': { skill: 'cooking', level: 10 },
	'Red Velvet Cake': { skill: 'cooking', level: 10 }
};

for (const [meal, gate] of Object.entries(COOKING_MEALS)) {
	gates[meal] = gate;
}

// Write static/recipe-levels.json & static/recipe-levels.sample.json
const jsonContent = JSON.stringify(gates, null, 2);
fs.writeFileSync(staticOutPath, jsonContent, 'utf8');
fs.writeFileSync(sampleOutPath, jsonContent, 'utf8');
console.log(`Wrote ${Object.keys(gates).length} recipe gates to ${staticOutPath}`);

// Write src/lib/quest/calc/recipeLevels.ts
const tsContent = `// Auto-generated by scripts/compile-recipe-levels.mjs — do not edit manually.
export interface RecipeGate {
	skill: 'crafting' | 'cooking';
	level: number;
	npc?: string;
	npcLevel?: number;
}

export type RecipeGateMap = Map<string, RecipeGate>;

export const RAW_RECIPE_GATES: Record<string, RecipeGate> = ${JSON.stringify(gates, null, 2)};

export const RECIPE_GATES: RecipeGateMap = new Map(Object.entries(RAW_RECIPE_GATES));

export function getRecipeGate(item: string): RecipeGate | undefined {
	return RECIPE_GATES.get(item);
}
`;

fs.writeFileSync(tsOutPath, tsContent, 'utf8');
console.log(`Wrote TypeScript definitions to ${tsOutPath}`);
